logger = structlog.get_logger()


def to_row(event: CapturedRequest) -> dict[str, Any]:
    """Map an event to a ``requests`` row. ``id`` is generated by the database."""
    return {
        "ts": event.ts,
        "event_id": event.event_id,
        "session_id": event.session_id,
        "world_id": event.world_id,
        "persona": event.persona,
        "ip": str(event.ip),
        "port": event.port,
        "ja4": event.ja4,
        "method": event.method,
        "path": event.path,
        "query": event.query,
        "headers": event.headers,
        "body_excerpt": event.body_excerpt,
        "body_size": event.body_size,
        "body_sha256": event.body_sha256,
        "body_truncated": event.body_truncated,
        "tier": event.tier,
        "status": event.status,
        "latency_ms": event.latency_ms,
        "tokens_used": event.tokens_used,
    }


class Persister(StreamConsumer):
    """Writes captured requests to Postgres with one multi-row INSERT per batch.

    Idempotent: a redelivered event hits ``ON CONFLICT (event_id, ts) DO NOTHING``.
    Keep ``batch_size`` below ~1500: asyncpg allows at most 32767 bind parameters
    per statement and a row uses 20.
    """

    def __init__(
        self,
        redis: Redis,
        stream: str,
        sessions: async_sessionmaker[AsyncSession],
        *,
        group: str = "persister",
        consumer: str | None = None,
        **kwargs: Any,
    ) -> None:
        super().__init__(
            redis, stream, group, consumer or f"{socket.gethostname()}-{os.getpid()}", **kwargs
        )
        self.sessions = sessions

    async def handle(self, entries: list[StreamEntry]) -> None:
        rows: list[dict[str, Any]] = []
        malformed = 0
        for _entry_id, fields in entries:
            try:
                rows.append(to_row(CapturedRequest.model_validate_json(fields["data"])))
            except (KeyError, ValidationError):
                malformed += 1
        if rows:
            statement = (
                insert(requests)
                .values(rows)
                .on_conflict_do_nothing(index_elements=["event_id", "ts"])
            )
            async with self.sessions.begin() as session:
                await session.execute(statement)
        if malformed:
            raise ValueError(f"{malformed} malformed event(s) in batch")


async def main() -> None:
    settings = Settings()
    configure_logging(settings.log_level)
    redis = Redis.from_url(settings.redis_url, decode_responses=True)
    engine = create_engine(settings.database_url.get_secret_value())
    persister = Persister(redis, settings.capture_stream, create_session_factory(engine))
    try:
        await run_until_signalled(persister)
    finally:
        await redis.aclose()
        await engine.dispose()


if __name__ == "__main__":
    asyncio.run(main())
